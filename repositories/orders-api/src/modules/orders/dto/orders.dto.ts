import { RejectionReasonCodeSchema } from 'contracts';
import { z } from 'zod';

// Shape checks only. Whether a quantity or a discount is acceptable is a
// business rule, answered with blocking reasons by the rule engine, so the
// screen can show them instead of a bare "400".
const LineSchema = z.object({
  productId: z.string().trim().min(1).max(40),
  quantity: z.number(),
  unit: z.enum(['UNIT', 'PACK']).default('UNIT'),
  // Basis points: 5% is 500.
  discountBp: z.number().default(0),
});

export const CalculateOrderSchema = z.object({
  clientId: z.string().trim().min(1).max(40),
  items: z.array(LineSchema).max(200),
  orderDiscountBp: z.number().default(0),
});
export type CalculateOrderDto = z.infer<typeof CalculateOrderSchema>;

export const SubmitOrderSchema = CalculateOrderSchema.extend({
  // Generated by the client for each order; sending it again returns the same order.
  orderId: z.uuid(),
});
export type SubmitOrderDto = z.infer<typeof SubmitOrderSchema>;

export const OrderIdSchema = z.uuid();

// The seller's history: the latest orders, newest first, of one client or,
// without a client, of all of them.
export const ListOrdersQuerySchema = z.object({
  clientId: z.string().trim().min(1).max(40).optional(),
  limit: z.coerce.number().int().min(1).max(50).default(10),
});
export type ListOrdersQuery = z.infer<typeof ListOrdersQuerySchema>;

// A supervisor rejects with one of the listed reasons; "other" needs a text.
export const RejectOrderSchema = z
  .object({
    reasonCode: RejectionReasonCodeSchema,
    reasonText: z.string().trim().max(500).optional(),
  })
  .refine((value) => value.reasonCode !== 'OTHER' || (value.reasonText?.length ?? 0) >= 3, {
    message: 'Describe the reason (at least 3 characters)',
    path: ['reasonText'],
  });
export type RejectOrderDto = z.infer<typeof RejectOrderSchema>;
